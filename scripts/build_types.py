@dataclass(order=True)
class Property:
    name: str
    can_write: bool = False
    can_read: bool = True

    def __hash__(self):
        return hash((self.name, self.can_read, self.can_write))

    def generate_code(self) -> str:
        # logic_type = "DevicesLogicType" if multiple else "DeviceLogicType"
        # return_type = "DevicesLogicType" if multiple else "float"
        name = self.name
        code = ""
        # args = []
        # if multiple:
        #     args.append("self._hash")
        # else:
        #     args.append("self")
        #     args.append("self._id")
        # args.append(f"'{name}'")
        # if multiple:
        #     args.append("self._name_hash")
        # args = ", ".join(args)

        if self.can_write:
            if typ := field_types.get(name):
                code += f"  {name}: _FieldDescW[{typ}] = _mk_field({typ})\n"
            else:
                code += f"  {name}: _FieldDescW = _mk_field()\n"
        elif self.can_read:
            if typ := field_types.get(name):
                code += f"  {name}: _FieldDesc[{typ}] = _mk_field_ro({typ})\n"
            else:
                code += f"  {name}: _FieldDesc = _mk_field_ro()\n"
        return code


@dataclass
class Structure:
    name: str
    id: int | None
    properties: set[Property]
    bases: set[str]
    extra: str = ""

    @staticmethod
    def create(
        name: str,
        *properties: Property,
        id: int | None = None,
        bases: list[str] = [],
        extra: str = "",
    ) -> Structure:
        return Structure(name, id, set(properties), set(bases), extra=extra)


def generate_generic_structure(struct: Structure) -> str:
    code = ""
    is_base = struct.id is None
    bases = (
        ", ".join([f"_DeviceTyped"] + [b for b in sorted(struct.bases)]) + ","
        if not is_base
        else ""
    )
    name = struct.name
    classname = name
    code += f"class {classname}({bases}):\n"
    if not is_base:
        code += f"  _hash: int = {struct.id}\n"
    # if multiple and not is_base:
    #     code += f"  def __getitem__(self, name: str | int) -> '{classname}':\n"
    #     code += f"      return {classname}(name)\n"

    for prop in sorted(struct.properties):
        code += prop.generate_code()

    code += struct.extra
    return code


